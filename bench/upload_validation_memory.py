#!/usr/bin/env python3
"""200k uploaded CSV rows; five fresh processes per case/mode/engine.
Run: python3 bench/upload_validation_memory.py
Inputs generated by parent, then read as bytes before timing in each child.
Modules loaded before timing; no query warmup. Peak RSS includes interpreter,
input, and result, sampled before output hashing. Output equality verified.
POSIX resource.getrusage required. Results written to cpython-validation-results.json.
"""
import csv, io, json, resource, sys, time
from pathlib import Path
ROOT = str(Path(__file__).resolve().parents[1])

def native_python(data, full):
    failures = []
    reader = csv.reader(io.TextIOWrapper(io.BytesIO(data), encoding='utf-8', newline=''))
    next(reader)
    for row in reader:
        if float(row[1]) < 0:
            if not full: return False
            failures.append({'values':row,'errors':[{'column':1,'column_name':'amount','rule':'below_min','value':row[1]}]})
    return failures if full else True

if len(sys.argv) > 1:
    engine, mode, path = sys.argv[1:]
    if engine in ('libscanio', 'json_bridge'):
        sys.path.insert(0, ROOT + '/python')
        import libscanio
        if engine == 'libscanio':
            from libscanio import _native
            assert _native.build_mode() == 'ReleaseFast'
        else:
            from libscanio import _loader
            import ctypes
            library = _loader.load()
            assert libscanio.build_mode() == 'ReleaseFast'
    data = Path(path).read_bytes()
    baseline = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    def json_bridge():
        pointer = library.scanio_validate_outcome(data, len(data), b'{"amount":{"type":"float","min":0}}', 1, mode == 'full')
        if not pointer: raise RuntimeError('JSON bridge failed')
        try: return json.loads(ctypes.string_at(pointer))
        finally: library.scanio_outcome_free(pointer)
    start = time.perf_counter_ns()
    result = libscanio.validate(data, {'amount':{'type':'float','min':0}}, mode=mode) if engine == 'libscanio' else json_bridge() if engine == 'json_bridge' else native_python(data, mode == 'full')
    elapsed = (time.perf_counter_ns() - start) / 1e6
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    import hashlib
    digest = hashlib.sha256(json.dumps(result,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    print(json.dumps(dict(ms=elapsed,peak_mib=peak/(1048576 if sys.platform == 'darwin' else 1024),baseline_mib=baseline/(1048576 if sys.platform == 'darwin' else 1024),digest=digest)))
else:
    import subprocess, tempfile, statistics, platform
    results = []
    with tempfile.TemporaryDirectory() as td:
        for case in ['valid','first_invalid','one_percent_invalid','all_invalid']:
            path = Path(td)/'input.csv'
            with path.open('w') as f:
                f.write('id,amount\n')
                for i in range(200000):
                    bad = case == 'all_invalid' or (case == 'first_invalid' and i == 0) or (case == 'one_percent_invalid' and i % 100 == 0)
                    f.write(f'{i},{-1 if bad else 10}\n')
            for mode in ['fast','full']:
                samples = {e:[] for e in ['libscanio','json_bridge','python']}
                for rep in range(5):
                    for engine in (['libscanio','json_bridge','python'] if rep%2==0 else ['python','json_bridge','libscanio']):
                        samples[engine].append(json.loads(subprocess.check_output([sys.executable,__file__,engine,mode,str(path)])))
                assert len({x['digest'] for v in samples.values() for x in v}) == 1
                item = dict(case=case, mode=mode, input_bytes=path.stat().st_size, samples=samples, medians={e:{k:statistics.median(x[k] for x in v) for k in ['ms','peak_mib','baseline_mib']} for e,v in samples.items()})
                results.append(item)
                print(case,mode,item['medians'],flush=True)
    Path('cpython-validation-results.json').write_text(json.dumps(dict(rows=200000,reps=5,platform=platform.platform(),python=platform.python_version(),results=results),indent=2))
